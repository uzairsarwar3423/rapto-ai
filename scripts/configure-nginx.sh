#!/usr/bin/env bash
# ==============================================================================
# Automated NGINX Ingress Configurator for Multi-App VPS
# Configures host NGINX to route api.rapto.cloud -> http://127.0.0.1:5010
# ==============================================================================
set -euo pipefail

DOMAIN="${1:-api.rapto.cloud}"
TARGET_PORT="${2:-5010}"
NGINX_CONF_DIR="/etc/nginx/sites-available"
NGINX_ENABLED_DIR="/etc/nginx/sites-enabled"
CONF_FILE="${NGINX_CONF_DIR}/${DOMAIN}.conf"

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🔧 Configuring NGINX for ${DOMAIN} -> 127.0.0.1:${TARGET_PORT}"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

# Check if Host NGINX is installed on the VPS OS
if command -v nginx &>/dev/null && [ -d "/etc/nginx" ]; then
    echo "🌐 Host NGINX detected on VPS. Setting up automated reverse proxy..."

    sudo mkdir -p "${NGINX_CONF_DIR}" "${NGINX_ENABLED_DIR}" /var/www/certbot

    # Check SSL Certificate presence
    SSL_CERT="/etc/letsencrypt/live/${DOMAIN}/fullchain.pem"
    SSL_KEY="/etc/letsencrypt/live/${DOMAIN}/privkey.pem"

    if [ -f "${SSL_CERT}" ] && [ -f "${SSL_KEY}" ]; then
        echo "🔒 SSL certificate found for ${DOMAIN}. Writing Full SSL + HTTP Redirect configuration..."
        cat <<EOF | sudo tee "${CONF_FILE}" > /dev/null
# ==============================================================================
# Managed NGINX Configuration for ${DOMAIN}
# Auto-generated by Rapto AI Deployment Pipeline
# ==============================================================================

# HTTP -> HTTPS Redirect & Certbot ACME Webroot
server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN};

    location /.well-known/acme-challenge/ {
        root /var/www/certbot;
        allow all;
    }

    location / {
        return 301 https://\$host\$request_uri;
    }
}

# HTTPS Reverse Proxy -> Rapto API Service (Port ${TARGET_PORT})
server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${DOMAIN};

    ssl_certificate ${SSL_CERT};
    ssl_certificate_key ${SSL_KEY};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384;
    ssl_prefer_server_ciphers off;
    ssl_session_timeout 1d;
    ssl_session_cache shared:SSL:10m;

    # Security Headers
    add_header X-Frame-Options "DENY" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-XSS-Protection "1; mode=block" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # Websocket / Socket.io Route
    location /socket.io/ {
        proxy_pass http://127.0.0.1:${TARGET_PORT};
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 86400s;
        proxy_send_timeout 86400s;
    }

    # Main API Routing
    location / {
        proxy_pass http://127.0.0.1:${TARGET_PORT};
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 60s;
        proxy_connect_timeout 60s;
        proxy_send_timeout 60s;
    }
}
EOF
    else
        echo "⚠️ SSL certificate not yet issued. Writing initial HTTP reverse proxy..."
        cat <<EOF | sudo tee "${CONF_FILE}" > /dev/null
# ==============================================================================
# Initial HTTP NGINX Configuration for ${DOMAIN}
# ==============================================================================
server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN};

    location /.well-known/acme-challenge/ {
        root /var/www/certbot;
        allow all;
    }

    location / {
        proxy_pass http://127.0.0.1:${TARGET_PORT};
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF
    # Purge any duplicate or legacy symlinks/configs to prevent "conflicting server name" warnings
    sudo rm -f "${NGINX_ENABLED_DIR}/${DOMAIN}" "${NGINX_ENABLED_DIR}/${DOMAIN}.conf" "${NGINX_CONF_DIR}/${DOMAIN}" "/etc/nginx/conf.d/${DOMAIN}.conf" "/etc/nginx/conf.d/${DOMAIN}"

    # Enable the site
    sudo ln -sf "${CONF_FILE}" "${NGINX_ENABLED_DIR}/${DOMAIN}.conf"

    # Test and Reload NGINX
    if sudo nginx -t; then
        sudo systemctl reload nginx || sudo systemctl restart nginx
        echo "✅ Host NGINX reloaded successfully! ${DOMAIN} -> 127.0.0.1:${TARGET_PORT}"
    else
        echo "⚠️ NGINX test failed. Please verify /etc/nginx/sites-available/${DOMAIN}.conf"
    fi
else
    echo "ℹ️ Host NGINX not installed. Dockerized NGINX container will serve the traffic."
fi
