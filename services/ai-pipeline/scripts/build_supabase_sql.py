"""Regenerate migrations/supabase_sql_editor_apply_all.sql from every *.up.sql (one atomic script for the Supabase SQL editor).

    python scripts/build_supabase_sql.py

Run it whenever a migration is added. The script is idempotent at the tracking level (INSERT … ON CONFLICT DO NOTHING) but
the migrations themselves are not: run it once on a database that has not had them applied (use `python -m src.rag.migrate status`).
It contains NO secrets; set the runtime role's password separately (ALTER ROLE vocaply_ai_app PASSWORD '…').
"""

from __future__ import annotations

import pathlib
import re

MIG = pathlib.Path(__file__).resolve().parent.parent / "migrations"
HEADER = """-- ═══════════════════════════════════════════════════════════════════════════════
-- RAG schema: ALL migrations in ONE script, for the Supabase SQL Editor.   (generated by scripts/build_supabase_sql.py)
--
-- RUN ONCE, as the default `postgres` role of a project that already has the Prisma tables
-- (teams, meetings, users, commitments, action_items, meeting_participants). Atomic: if any statement fails, nothing is kept.
-- It records the migrations in rag.schema_migrations so `python -m src.rag.migrate status` agrees.
-- Afterwards set the runtime role's password yourself (this script never contains a secret):
--     ALTER ROLE vocaply_ai_app PASSWORD '<strong secret>';
-- ═══════════════════════════════════════════════════════════════════════════════
BEGIN;
SET LOCAL search_path = rag, extensions, public;

CREATE SCHEMA IF NOT EXISTS rag;
CREATE TABLE IF NOT EXISTS rag.schema_migrations (version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());
"""


def main() -> None:
    parts = [HEADER]
    for path in sorted(MIG.glob("*.up.sql")):
        version = re.sub(r"\.up\.sql$", "", path.name)
        parts.append(f"\n-- ───────── {version} ─────────\n{path.read_text(encoding='utf-8').rstrip()}\n")
        parts.append(f"INSERT INTO rag.schema_migrations (version) VALUES ('{version}') ON CONFLICT DO NOTHING;\n")
    parts.append("\nCOMMIT;\n")
    out = MIG / "supabase_sql_editor_apply_all.sql"
    out.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {out} ({len(''.join(parts))} bytes)")


if __name__ == "__main__":
    main()
