"""
eval/eval_schema.py
───────────────────
Expected-output schema for golden dataset fixtures (`*_expected.json`).

Every criterion except `text_contains` is optional: an unset criterion is
skipped by the matcher, never failed. Older fixtures (commitments/action items
only, no meeting_type) still load — all new fields have defaults.
"""

from typing import List, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field

from src.models.extraction_models import (
    DecisionType,
    PriorityLevel,
    RiskCategory,
    SeverityLevel,
)


class _Expected(BaseModel):
    # Fixtures may carry free-form notes next to criteria.
    model_config = ConfigDict(extra="ignore")


class EvalExpectedCommitment(_Expected):
    text_contains: Optional[str] = None
    owner_name_contains: str
    confidence_min: Optional[float] = None
    due_date_raw_contains: Optional[str] = None


class EvalExpectedActionItem(_Expected):
    text_contains: str
    assignee_name_contains: str
    priority: Optional[PriorityLevel] = None


class EvalExpectedDecision(_Expected):
    text_contains: str
    decision_type: Optional[DecisionType] = None
    confidence_min: Optional[float] = None
    reversible: Optional[bool] = None             # v3.1 field


class EvalExpectedBlocker(_Expected):
    text_contains: str
    blocked_work_contains: Optional[str] = None
    severity: Optional[SeverityLevel] = None
    escalation_expected: Optional[bool] = None    # v3.1 field


class EvalExpectedRisk(_Expected):
    text_contains: str
    category: Optional[RiskCategory] = None
    trigger_condition_contains: Optional[str] = None
    probability: Optional[Literal["LOW", "MEDIUM", "HIGH"]] = None  # v3.1 field


class EvalExpectedSummary(_Expected):
    key_phrase_in_overview: Optional[str] = None
    required_topics: Optional[List[str]] = None
    min_key_takeaways: Optional[int] = None
    # Human-written reference summary for ragas context_recall / similarity.
    # When absent, ragas_harness synthesizes one from the golden expectations.
    reference_summary: Optional[str] = None


class EvalCase(_Expected):
    meeting_id: str
    meeting_type: str = "general"                 # for prompt routing in eval
    meeting_title: Optional[str] = None
    description: str = ""
    expected_commitments: List[EvalExpectedCommitment] = Field(default_factory=list)
    expected_action_items: List[EvalExpectedActionItem] = Field(default_factory=list)
    expected_decisions: List[EvalExpectedDecision] = Field(default_factory=list)
    expected_blockers: List[EvalExpectedBlocker] = Field(default_factory=list)
    expected_risks: List[EvalExpectedRisk] = Field(default_factory=list)
    expected_summary: Optional[EvalExpectedSummary] = None
    expected_commitment_count: int = 0
    expected_zero_commitments: bool = False
    # Extractors this fixture is labelled for. Unlabelled extractors are not
    # scored for the fixture (an empty list would otherwise count every
    # extracted item as a false positive). None = all extractors labelled.
    labelled_extractors: Optional[List[str]] = None
    # True for expectations generated by fixtures_builder.py from model output.
    # Drafts are skipped by the runners until a human reviews them and flips
    # this to false — scoring a model against its own output proves nothing.
    draft: bool = False
